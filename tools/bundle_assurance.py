#!/usr/bin/env python3
"""Write the Assurance agent's one-file AgentCore handler (G-01; ARCH 3.11, 7.3; plan T6.1).

  python3 tools/bundle_assurance.py            # writes agents/ifabric-assurance/ifabric-assurance.py
  python3 tools/bundle_assurance.py --check    # exit 1 if the committed file differs from a fresh build

The output = a generated importlib loader that serves Arth's nemotron.py BYTE-IDENTICAL (plus the two empty
package markers it needs) from an embedded dict, followed by our shim (agents/ifabric-assurance/
assurance_shim.py). It embeds nothing else of Arth's. The kit's CI gate measures gzip+base64 of the file;
this refuses to write anything over the gate (the work/13 R3 prototype measured ~5.8K).
Stdlib only, Python 3.9. Never writes a file named agent.py.
"""
import argparse
import base64
import gzip
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARTH = os.path.join("handoffs", "ifabric-handoff-3", "code")
EMBED = (  # (module name, path under ARTH); the master is Arth's package, used as-is
    ("prooflab", "prooflab/__init__.py"),
    ("prooflab.servicenow", "prooflab/servicenow/__init__.py"),
    ("prooflab.servicenow.nemotron", "prooflab/servicenow/nemotron.py"),
)
PACKAGES = ("prooflab", "prooflab.servicenow")
SHIM = os.path.join("agents", "ifabric-assurance", "assurance_shim.py")
OUT = os.path.join("agents", "ifabric-assurance", "ifabric-assurance.py")
SIZE_GATE = 24000  # the build path's CI gate on gzip+base64 chars (BUILD-SESSION-PROMPT hard constraints)

HEADER = '''# ifabric-assurance.py: GENERATED by tools/bundle_assurance.py. Do not edit; regenerate.
# The 4th AgentCore runtime (ifabric-assurance-agent): Arth's handoff-3 nemotron.py, byte-identical,
# served by the importlib finder below, then our shim. Embedded sha256: %(shas)s
'''

LOADER = '''import importlib.abc
import importlib.util
import sys as _sys

_SOURCES = {
%(sources)s}
_PACKAGES = %(packages)r
_ORIGIN = "/app/_bundle"


class _BundleFinder(importlib.abc.MetaPathFinder, importlib.abc.Loader):
    """Serves the embedded modules; each keeps its own namespace and is in sys.modules before exec (work/13 R4)."""

    def find_spec(self, name, path=None, target=None):
        if name not in _SOURCES:
            return None
        rel = name.replace(".", "/") + ("/__init__.py" if name in _PACKAGES else ".py")
        return importlib.util.spec_from_file_location(
            name, _ORIGIN + "/" + rel, loader=self,
            submodule_search_locations=[] if name in _PACKAGES else None)

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        exec(compile(_SOURCES[module.__name__], module.__file__, "exec"), module.__dict__)


_sys.meta_path.insert(0, _BundleFinder())
'''


def _read(root, rel):
    with open(os.path.join(root, rel), "rb") as fh:
        return fh.read()


def build(root=ROOT):
    """Return the generated file's text (deterministic for the same inputs)."""
    entries, shas = [], []
    for name, rel in EMBED:
        raw = _read(root, os.path.join(ARTH, rel))
        text = raw.decode("utf-8")
        if text.encode("utf-8") != raw:
            raise ValueError("%s does not round-trip as UTF-8" % rel)
        entries.append("    %r: %r,\n" % (name, text))
        shas.append("%s=%s" % (name.rsplit(".", 1)[-1], hashlib.sha256(raw).hexdigest()))
    shim = _read(root, SHIM).decode("utf-8")
    loader = LOADER % {"sources": "".join(entries), "packages": PACKAGES}
    return HEADER % {"shas": " ".join(shas)} + loader + "\n\n" + shim


def gate_size(text):
    """gzip -9 (no name, mtime 0) then base64, as the CI gate measures it."""
    return len(base64.b64encode(gzip.compress(text.encode("utf-8"), 9, mtime=0)))


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--root", default=ROOT, help="repo root (default: this script's repo)")
    p.add_argument("--out", default=None, help="output path (default: %s)" % OUT)
    p.add_argument("--check", action="store_true", help="compare with the committed file; write nothing")
    a = p.parse_args(argv)
    out = a.out or os.path.join(a.root, OUT)
    if os.path.basename(out) != "ifabric-assurance.py":
        print("bundle_assurance: the output must be named ifabric-assurance.py", file=sys.stderr)
        return 2
    text = build(a.root)
    size = gate_size(text)
    report = {"bundle": os.path.relpath(out, a.root), "gzip_base64_chars": size, "gate": SIZE_GATE,
              "raw_bytes": len(text.encode("utf-8")), "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest()}
    if size > SIZE_GATE:
        report["result"] = "REFUSED: over the size gate"
        print(json.dumps(report, sort_keys=True))
        return 1
    if a.check:
        try:
            same = _read(a.root, os.path.relpath(out, a.root)) == text.encode("utf-8")
        except OSError:
            same = False
        report["result"] = "up to date" if same else "STALE: regenerate"
        print(json.dumps(report, sort_keys=True))
        return 0 if same else 1
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    report["result"] = "written"
    print(json.dumps(report, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
